function hexToRgba(hex: string, alpha: number): string {
  const h = hex.replace("#", "");
  const r = parseInt(h.slice(0, 2), 16);
  const g = parseInt(h.slice(2, 4), 16);
  const b = parseInt(h.slice(4, 6), 16);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

export function terminalThemeFor(theme: Theme): TerminalTheme {
  const colors = themes[theme]?.colors ?? themes.dark.colors;
  const ansi = terminalThemes[theme] ?? FALLBACK_ANSI;
  return {
    background: colors.background,
    foreground: colors.text,
    cursor: colors.text,
    cursorAccent: colors.background,
    selectionBackground: hexToRgba(colors.primary, 0.3),
    ...ansi,
  };
}

