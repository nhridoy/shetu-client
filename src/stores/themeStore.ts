// Themes carry no light/dark flag, so judge by the background's brightness.
export function isLightTheme(theme: Theme): boolean {
  const hex = themes[theme]?.colors.background ?? "#000000";
  const [r, g, b] = [1, 3, 5].map((i) =>
    Number.parseInt(hex.slice(i, i + 2), 16),
  );
  return 0.299 * r + 0.587 * g + 0.114 * b > 128;
}

export function applyTheme(theme: Theme) {
  const themeData = themes[theme];
  if (!themeData) return;
  const root = document.documentElement;
  for (const [key, cssVar] of Object.entries(CSS_VAR_MAP)) {
    const value = themeData.colors[key as keyof ThemeColors];
    if (value) root.style.setProperty(cssVar, value);
  }
}

interface ThemeState {
  currentTheme: Theme;
  setTheme: (theme: Theme) => Promise<void>;
  initTheme: () => Promise<void>;
}

const STORE_KEY = "settings.json";

export const useThemeStore = create<ThemeState>((set) => ({
  currentTheme: "dark",
  setTheme: async (theme) => {
    set({ currentTheme: theme });
    applyTheme(theme);
    try {
      const store = await load(STORE_KEY, { autoSave: false });
      await store.set("theme", theme);
      await store.save();
    } catch {
      // best-effort: theme still applies for this session
    }
  },
  initTheme: async () => {
    let theme: Theme = "dark";
    try {
      const store = await load(STORE_KEY, { autoSave: false });
      const saved = await store.get<Theme>("theme");
      if (saved && themes[saved]) theme = saved;
    } catch {
      // keep default dark
    }
    set({ currentTheme: theme });
    applyTheme(theme);
  },
}));
